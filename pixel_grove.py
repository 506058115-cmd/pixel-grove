#!/usr/bin/env python3
"""Create a seedable, self-contained SVG forest at twilight."""

import argparse
import random
import secrets
import sys
from pathlib import Path


def between(rng, low, high):
    return low + rng.random() * (high - low)


def points_text(points):
    return " ".join(f"{x:.1f},{y:.1f}" for x, y in points)


def ridge(rng, width, height, base, lift, count, color):
    step = width / count
    points = [(0, height), (0, base)]
    for index in range(1, count):
        x = step * index + between(rng, -step * 0.16, step * 0.16)
        y = base - between(rng, lift * 0.28, lift)
        points.append((x, y))
    points.extend(((width, base), (width, height)))
    return f'<polygon points="{points_text(points)}" fill="{color}"/>'


def pine(x, base, size, color, highlight):
    width = size * 0.38
    top = base - size
    layers = []
    for start, end, spread in ((0.08, 0.48, 0.56), (0.31, 0.72, 0.82), (0.55, 0.91, 1.0)):
        y1 = top + size * start
        y2 = top + size * end
        half = width * spread
        layers.append(
            f'<polygon points="{x:.1f},{y1:.1f} {x - half:.1f},{y2:.1f} '
            f'{x + half:.1f},{y2:.1f}" fill="{color}"/>'
        )
    trunk_top = base - size * 0.17
    trunk_half = max(1.4, size * 0.035)
    layers.append(
        f'<path d="M{x - trunk_half:.1f},{trunk_top:.1f} '
        f'L{x + trunk_half:.1f},{trunk_top:.1f} L{x + trunk_half:.1f},{base:.1f} '
        f'L{x - trunk_half:.1f},{base:.1f}Z" fill="{highlight}" opacity=".8"/>'
    )
    return "".join(layers)


def tree_layer(rng, width, height, count, base, scale, color, trunk):
    spacing = width / count
    trees = []
    for index in range(count):
        x = spacing * (index + 0.5) + between(rng, -spacing * 0.28, spacing * 0.28)
        size = height * between(rng, scale * 0.72, scale * 1.25)
        trees.append(pine(x, base, size, color, trunk))
    return "".join(trees)


def make_svg(width, height, seed, trees):
    rng = random.Random(seed)
    scale = min(width / 960, height / 600)
    moon_x, moon_y, moon_r = width * 0.77, height * 0.23, 38 * scale
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
        '<title>Pixel Grove</title>',
        f'<desc>A seed {seed} twilight forest generated by pixel-grove.</desc>',
        '<defs><linearGradient id="sky" x2="0" y2="1">'
        '<stop stop-color="#17253e"/><stop offset=".56" stop-color="#536777"/>'
        '<stop offset="1" stop-color="#e39a78"/></linearGradient></defs>',
        f'<rect width="{width}" height="{height}" fill="url(#sky)"/>',
    ]

    star_count = max(18, width * height // 20000)
    for _ in range(star_count):
        x, y = between(rng, 12, width - 12), between(rng, 12, height * 0.56)
        if (x - moon_x) ** 2 + (y - moon_y) ** 2 > (moon_r * 1.55) ** 2:
            radius = between(rng, 0.7, 1.8) * scale
            opacity = between(rng, 0.34, 0.88)
            parts.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{radius:.1f}" fill="#fff0c4" opacity="{opacity:.2f}"/>')

    parts.extend((
        f'<circle cx="{moon_x:.1f}" cy="{moon_y:.1f}" r="{moon_r:.1f}" fill="#f7d9a1" opacity=".95"/>',
        f'<circle cx="{moon_x - moon_r * 0.27:.1f}" cy="{moon_y - moon_r * 0.28:.1f}" r="{moon_r * 0.13:.1f}" fill="#e6bb8a" opacity=".45"/>',
        f'<circle cx="{moon_x + moon_r * 0.31:.1f}" cy="{moon_y + moon_r * 0.18:.1f}" r="{moon_r * 0.08:.1f}" fill="#e6bb8a" opacity=".38"/>',
        ridge(rng, width, height, height * 0.77, height * 0.22, 11, "#354b59"),
        tree_layer(rng, width, height, trees, height * 0.84, 0.19, "#526b63", "#947462"),
        ridge(rng, width, height, height * 0.88, height * 0.10, 15, "#29494b"),
        f'<path d="M0,{height * 0.88:.1f} Q{width * 0.23:.1f},{height * 0.82:.1f} {width * 0.48:.1f},{height * 0.9:.1f} '
        f'T{width},{height * 0.86:.1f} V{height} H0Z" fill="#18383d"/>',
    ))

    for _ in range(max(6, trees // 2)):
        x, y = between(rng, 0, width), between(rng, height * 0.88, height * 0.98)
        parts.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{between(rng, 1.0, 2.1) * scale:.1f}" fill="#f5cb86" opacity=".68"/>')

    parts.append(tree_layer(rng, width, height, trees, height * 1.02, 0.29, "#112f36", "#594a3c"))
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Generate a seedable twilight forest as a standalone SVG.")
    parser.add_argument("--seed", type=int, help="recreate a scene with a seed from 0 to 4294967295")
    parser.add_argument("--width", type=int, default=960, help="image width in pixels (320–1600)")
    parser.add_argument("--height", type=int, default=600, help="image height in pixels (240–1200)")
    parser.add_argument("--trees", type=int, default=22, help="pine density per forest row (8–48)")
    parser.add_argument("--output", type=Path, help="write to a new file; default is standard output")
    args = parser.parse_args()

    if not 320 <= args.width <= 1600 or not 240 <= args.height <= 1200:
        parser.error("--width must be 320–1600 and --height 240–1200")
    if not 8 <= args.trees <= 48:
        parser.error("--trees must be between 8 and 48")
    if args.seed is not None and not 0 <= args.seed <= 0xFFFFFFFF:
        parser.error("--seed must be between 0 and 4294967295")

    seed = args.seed if args.seed is not None else secrets.randbits(32)
    svg = make_svg(args.width, args.height, seed, args.trees)
    if args.output is None:
        sys.stdout.write(svg)
        return 0

    try:
        with args.output.open("x", encoding="utf-8", newline="\n") as output:
            output.write(svg)
    except FileExistsError:
        parser.exit(2, f"pixel-grove: refusing to overwrite {args.output}\n")
    except OSError as error:
        parser.exit(2, f"pixel-grove: {error}\n")
    print(f"Wrote {args.output} (seed {seed})", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
